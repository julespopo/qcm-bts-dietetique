#!/usr/bin/env python3
"""Produce both standalone editions from the same HTML, CSS and JavaScript."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='fail if a generated page is stale; do not write')
args = parser.parse_args()
source = ROOT / 'src'
template = (source / 'page.html').read_text(encoding='utf-8')
shared = {
    '@@STYLES@@': (source / 'styles.css').read_text(encoding='utf-8'),
    '@@SCRIPT@@': (source / 'app.js').read_text(encoding='utf-8'),
}
stale = []
for edition, filename in [('web', 'index.html'), ('local', 'index_local.html')]:
    values = {**shared, '@@EDITION@@': edition, '@@LOCAL_LOADER@@': (source / 'local-loader.html').read_text(encoding='utf-8') if edition == 'local' else ''}
    output = template
    for marker, value in values.items():
        output = output.replace(marker, value)
    output = output.replace('<!doctype html>', '<!doctype html>\n<!-- Generated by scripts/build.py; edit src/ instead. -->', 1)
    path = ROOT / filename
    if args.check:
        if not path.exists() or path.read_text(encoding='utf-8') != output:
            stale.append(filename)
    else:
        path.write_text(output, encoding='utf-8')
if stale:
    parser.exit(1, 'Pages obsolètes : ' + ', '.join(stale) + '. Lancer python3 scripts/build.py.\n')
print('OK — pages générées ' + ('à jour' if args.check else 'depuis src/'))
